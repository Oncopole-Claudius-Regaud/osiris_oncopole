SELECT
    CP_NUMDOSS AS NUM_DOSS,
    CP_NUM_J AS JOUR,
    CP_DATE_ADM AS DAT_ADMINI,
    NULL AS COD_CATEG_PROTO,
    CP_LIB_TYPE_PDT AS COD_TYP_PROTO,
    CP_CODE_PDT AS NUM_PDT,
    COALESCE(CP_LIB_UCD, CP_LIB_PDT) AS NOM_PDT,
    CP_CODE_VOIE_ADM AS COD_VOIE,
    CP_CODE_SERV AS UF_REAL,
    CP_LIB_SERV AS LIB_UF_REAL,
    COALESCE(CP_QTE_PDT_UTILISEE, CP_DOSE_PREVUE) AS DOSE_TOT,
    CP_NUMPLAN_ICR AS NOM_PROTO,
    CP_LIB_TYPE_PDT AS NOM_MODA,
    COALESCE(CP_STATUT, CP_ETAT) AS CE_ETAT_CHIMIO
FROM
    DMI_ICR.CHIMIO_PRESCRIPTION C
