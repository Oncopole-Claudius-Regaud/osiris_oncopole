SELECT
    C.CP_NUMDOSS AS NUM_DOSS,
    C.CP_NUM_J AS JOUR,
    C.CP_DATE_ADM AS DAT_ADMINI,
    C.CP_LIB_TYPE_PDT AS COD_TYP_PROTO,
    C.CP_CODE_PDT AS NUM_PDT,
    C.CP_LIB_UCD AS NOM_PDT,
    C.CP_CODE_VOIE_ADM AS COD_VOIE,
    C.CP_CODE_SERV AS UF_REAL,
    C.CP_LIB_SERV AS LIB_UF_REAL,
    COALESCE(C.CP_QTE_PDT_UTILISEE, C.CP_DOSE_PREVUE) AS DOSE_TOT,
    C.CP_LIB_TYPE_PDT AS NOM_MODA,
    COALESCE(C.CP_STATUT, C.CP_ETAT) AS CE_ETAT_CHIMIO,
    C.CP_CODE_UCD AS CODE_UCD,
    C.CP_CODE_DCI AS CODE_DCI,
    C.CP_LIB_DCI AS LIB_DCI,
    C.CP_LIB_UCD AS LIB_UCD,
    C.CP_CODE_VOIE_ADM AS CP_CODE_VOIE_ADM,
    C.CP_LIB_MED_PRESC AS CP_LIB_MED_PRESC,
    C.CP_CODE_DCI AS CP_CODE_DCI,
    C.CP_NUM_CURE AS NUM_CYCLE
FROM DMI_ICR.CHIMIO_PRESCRIPTION C
WHERE
    UPPER(TRIM(C.CP_LIB_ETAPE_PRESC)) = 'ADMINISTRE'
